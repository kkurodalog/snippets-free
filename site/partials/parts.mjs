/**
 * タグの語彙。データ側でこれ以外を書いたら生成を止める（表記ゆれでフィルタが割れるため）。
 *
 * ★**この配列の並び順が、そのまま画面の chip の並び順になる**（`site/templates/category.mjs`）。
 *   語彙と並び順を同じ1本で持つ。2本に分けると、タグを足したときに
 *   「語彙には入れたが並び順に入れ忘れる」という食い違いが必ず生まれる。
 *
 * ★並べる規則 — **必要な要素が少ないものから順に左から並べる**。
 *   「すべて」は左端に固定し、この配列はその右隣から始まる。
 *     1. CSSのみ           … HTML と CSS だけで動く（用意するものが最も少ない）
 *     2. JS必要            … 上に JS が加わる
 *     3. scroll-driven CSS … 上に「その機能を持つブラウザ」という前提が加わる
 *     4. 画像素材あり      … 上に「利用者が自分で用意する画像」が加わる
 *                            （コードを写しただけでは完成しない唯一のタグ）
 *
 * ⚠️ **3位と4位（scroll-driven CSS / 画像素材あり）の順を勝手に入れ替えない。**
 *    現行のパーツでは「**画像素材あり を持つものは、必ず scroll-driven CSS も持つ**」
 *    という包含になっており、上の規則からそのまま現行順が導ける。
 *    ⚠️ ★この根拠は将来ほどける — **scroll-driven CSS を持たない「画像素材あり」のパーツ**
 *       （例: 画像を使う CSS のみのカード）を足すと包含が崩れ、規則だけでは順序が決まらなくなる。
 *       そのときは並べ替える前に★代表判断へ戻す（2026-08-18 の★代表判断で現行順に確定している）。
 *
 * ⚠️ ここに無いタグを使ったデータは `tools/build.mjs` が違反として生成を止める。
 *    並び順の側では末尾へ送る（下記 `tagOrder`）。**黙って任意の順で出さない。**
 */
export const TAGS = ['CSSのみ', 'JS必要', 'scroll-driven CSS', '画像素材あり'];

/**
 * 並び順の索引。小さいほど左に出る。
 *
 * ⚠️ 語彙に無いタグでも**例外を投げない**。生成の流れは「先に全ページを組み立て、
 *    最後にまとめて違反を報告する」形であり（`tools/build.mjs` の (6)）、
 *    ここで投げると**その1件だけを持って落ち、他の違反が報告されない**。
 *    並びは末尾へ寄せ、落とす判定は build 側の「未定義のタグ」に任せる。
 * ⚠️ 末尾へ寄せたもの同士の順序は、`Array.prototype.sort` が安定なので
 *    データに現れた順のまま保たれる（実行のたびに入れ替わらない）。
 */
export function tagOrder(tag) {
  const index = TAGS.indexOf(tag);
  return index === -1 ? TAGS.length : index;
}

